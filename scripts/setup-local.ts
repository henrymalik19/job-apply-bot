// Local dev only: creates a test owner in the local Supabase stack and writes
// .env.local with the local keys and owner credentials. Refuses non-local URLs.
//   pnpm setup:local
import { execSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createServiceClient } from "@/server/db/service-client";
import { setOwner } from "@/server/auth/owner.repository";

const ENV_FILE = ".env.local";

function localStatus() {
  const out = execSync("pnpm exec supabase status -o json", { encoding: "utf8" });
  const s = JSON.parse(out.slice(out.indexOf("{")));
  if (!/^http:\/\/(127\.0\.0\.1|localhost)[:/]/.test(s.API_URL ?? "")) {
    throw new Error("local Supabase is not running (pnpm db:start)");
  }
  return { url: s.API_URL as string, anonKey: s.ANON_KEY as string, serviceRoleKey: s.SERVICE_ROLE_KEY as string };
}

function readEnv(): Record<string, string> {
  if (!existsSync(ENV_FILE)) return {};
  return Object.fromEntries(
    readFileSync(ENV_FILE, "utf8").split(/\r?\n/)
      .filter((l) => /^[A-Z0-9_]+=/.test(l))
      .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]),
  );
}

async function main() {
  const { url, anonKey, serviceRoleKey } = localStatus();
  const existing = readEnv();
  const db = createServiceClient({ SUPABASE_URL: url, SUPABASE_SERVICE_ROLE_KEY: serviceRoleKey });

  const email = existing.LOCAL_OWNER_EMAIL || "owner@example.test";
  const password = existing.LOCAL_OWNER_PASSWORD || randomBytes(18).toString("base64url");

  // Reuse the user if it exists (e.g. after a re-run), otherwise create it.
  const { data: list, error: listErr } = await db.auth.admin.listUsers();
  if (listErr) throw listErr;
  let user = list.users.find((u) => u.email === email);
  if (user) {
    const { error } = await db.auth.admin.updateUserById(user.id, { password });
    if (error) throw error;
  } else {
    const { data, error } = await db.auth.admin.createUser({ email, password, email_confirm: true });
    if (error) throw error;
    user = data.user;
  }

  await setOwner(db, user.id);

  const env = {
    ...existing,
    SUPABASE_URL: url,
    SUPABASE_ANON_KEY: anonKey,
    SUPABASE_SERVICE_ROLE_KEY: serviceRoleKey,
    OWNER_USER_ID: user.id,
    LOCAL_OWNER_EMAIL: email,
    LOCAL_OWNER_PASSWORD: password,
  };
  writeFileSync(
    ENV_FILE,
    "# Local dev only. Generated by `pnpm setup:local`. Never commit.\n" +
      Object.entries(env).map(([k, v]) => `${k}=${v}`).join("\n") + "\n",
  );
  // Credentials stay in .env.local; print only non-secret facts.
  console.log(JSON.stringify({ ok: true, owner: user.id, email, envFile: ENV_FILE }));
}

main().catch((err) => {
  console.error(JSON.stringify({ ok: false, error: String(err.message ?? err) }));
  process.exit(1);
});
